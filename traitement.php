$email = $_POST['email'];
$sujet = $_POST['sujet'];
$message=$_POST['message'];

$message = "Nom : ".$nom."\n"."Email : ".$email."\n"."message : ".$message;

try {
    //Server settings
    $mail->isSMTP();                                            //Send using SMTP
    $mail->Host       = 'smtp.gmail.com';                     //Set the SMTP server to send through
